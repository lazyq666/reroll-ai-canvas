/* Real-page integration checks, launched by the isolated fixture's visible button. */
window.runImageRepairChecks = async function(){
    const report=document.getElementById('fixture-result');
    report.textContent='Running…';
    const $=id=>document.getElementById(`imageRepair${id}`);
    const assert=(condition,message)=>{if(!condition)throw new Error(message);};
    const until=async(check,message)=>{
        const deadline=Date.now()+15000;
        while(Date.now()<deadline){if(await check())return;await new Promise(r=>setTimeout(r,40));}
        throw new Error(message);
    };
    const edit=(id,value,event='change')=>{$(id).value=String(value);$(id).dispatchEvent(new Event(event,{bubbles:true}));};
    const state=()=>fetch('/fixture/state').then(r=>r.json());
    const canvasDataForRepairDiagnostics=()=>canvas.logs.find(log=>log.tasks?.some(task=>task.errorCode==='repair_invalid'));
    const settle=()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
    const editor=window.SmartCanvasModules.imageStudio;
    const open=async nodeId=>{
        editor.open({nodeId,mode:'local-repair'});
        await until(()=>$('Status').textContent!==tr('smart.repair.loading'),'editor load');
        await settle();
    };
    try {
        window.StudioI18n.set('zh');
        await open('layer-source');
        assert($('Model').value==='flagship','flagship model preference');
        $('Settings').dispatchEvent(new CustomEvent('ic-change',{detail:{field:'ratio',value:'adaptive'}}));
        $('Clear').click();$('Rectangle').click();
        const canvas=$('Canvas'),rect=canvas.getBoundingClientRect();
        const pointer=(type,x,y)=>canvas.dispatchEvent(new PointerEvent(type,{pointerId:1,button:0,bubbles:true,clientX:rect.x+x*rect.width,clientY:rect.y+y*rect.height}));
        // Synthetic events cannot capture a native pointer; the fixture brackets that DOM API only.
        const capture=canvas.setPointerCapture;canvas.setPointerCapture=()=>{};
        pointer('pointerdown',.38,.50);pointer('pointermove',.52,.67);pointer('pointerup',.52,.67);
        canvas.setPointerCapture=capture;
        assert(!$('CropPreview').hidden,'crop preview');
        const size=$('CropSize').textContent;
        assert(size.includes('1:1'),'standard ratio');
        assert($('Settings').resolution==='1K','nearest tier');
        assert($('Model').dataset.componentVariant==='model-picker','composer model picker variant');
        assert($('Settings').localName==='ic-generation-settings-picker','composer size picker');
        assert($('Presets').children.length===6,'six preset tags');
        $('Presets').querySelector('[data-preset="hand"]').click();
        assert($('Prompt').value.startsWith('Fix the hand anatomy: exactly five fingers'),'preset content');
        assert($('Prompt').value.endsWith('Do not redesign unaffected areas.'),'shared suffix');
        assert($('Prompt').value.includes('Keep the repaired area precisely aligned with the source image.'),'suffix keeps spatial alignment');
        const wheel=new WheelEvent('wheel',{deltaY:120,bubbles:true,composed:true,cancelable:true});
        $('Prompt').dispatchEvent(wheel);
        assert(!wheel.defaultPrevented,'prompt retains native scrolling');
        assert(!document.querySelector('[data-i18n="smart.repair.presetsHint"],[data-i18n="smart.repair.resizeHint"]'),'removed helper copy');
        window.StudioI18n.set('en');
        assert($('Presets').firstElementChild.textContent==='Hand anatomy / extra fingers','preset language switch');
        assert($('Settings').getAttribute('adaptive-label')==='Auto frame','picker language switch');
        window.StudioI18n.set('zh');
        edit('Prompt','Remove the dark mark','input');
        await settle();
        $('Undo').click();assert($('Generate').disabled,'undo clears selection');
        canvas.dispatchEvent(new KeyboardEvent('keydown',{key:'z',ctrlKey:true,shiftKey:true,bubbles:true}));
        assert(!$('Generate').disabled,'redo restores selection');
        const initialDraft=nodes.find(n=>n.id==='layer-source').localRepairDrafts['layer-source-media'];
        const crop=initialDraft.box;
        const edgeX=(crop.x+crop.width)/1000,edgeY=(crop.y+crop.height/2)/800;
        canvas.setPointerCapture=()=>{};
        pointer('pointerdown',edgeX,edgeY);pointer('pointermove',edgeX+.08,edgeY);pointer('pointerup',edgeX+.08,edgeY);
        canvas.setPointerCapture=capture;
        const resized=nodes.find(n=>n.id==='layer-source').localRepairDrafts['layer-source-media'].box;
        assert(resized.width>crop.width&&resized.width/resized.height===crop.width/crop.height,'border drag enlarges fixed ratio');
        assert(nodes.find(n=>n.id==='layer-source').localRepairDrafts['layer-source-media'].strokes.length===1,'border drag does not paint');
        const expandedSize=$('CropSize').textContent;
        assert(!$('Transparent').hidden,'supported transparency shown');
        edit('Count',3);
        $('Transparent').checked=true;$('Transparent').dispatchEvent(new Event('change',{bubbles:true}));
        edit('Model','gpt2');
        assert($('Count').value==='1','model count limit clamps selection');
        assert($('Transparent').hidden&&!$('Transparent').checked,'unsupported model clears transparency');
        edit('Model','flagship');
        edit('Count',3);
        $('Transparent').checked=true;$('Transparent').dispatchEvent(new Event('change',{bubbles:true}));
        $('Settings').dispatchEvent(new CustomEvent('ic-change',{detail:{field:'resolution',value:'2K'}}));
        editor.close();await open('layer-source');
        assert($('Transparent').checked&&$('Settings').resolution==='2K','output options survive reopen');
        assert($('Count').value==='3','count survives reopen');
        assert($('CropSize').textContent===expandedSize,'selection draft survives reopen');
        assert($('Prompt').value==='Remove the dark mark','prompt draft survives reopen');
        assert(!$('Close'),'no text close button');
        await fetch('/fixture/reject-next',{method:'POST'});
        $('Generate').click();
        await until(()=>$('Status').textContent===tr('smart.repair.failed'),'submission failure shown');
        assert(!$('Editor').hidden&&$('Prompt').value==='Remove the dark mark','submission failure retains editor and prompt');
        const failure=canvasDataForRepairDiagnostics();
        assert(failure?.tasks?.[0]?.httpStatus===422&&failure.tasks[0].errorCode==='repair_invalid','submission diagnostics retain status and code');
        for(const lang of ['en','zh']){
            window.StudioI18n.set(lang);
            const reason=await smartResponseErrorMessage(new Response(JSON.stringify({detail:{code:'repair_invalid'}}),{status:422}),tr('smart.errRunFailed'));
            assert(reason===tr('smart.repair.invalid')&&reason!==tr('smart.errRunFailed'),'repair error follows language');
        }
        const before=(await state()).submissions.length;
        const previousIds=new Set(nodes.map(n=>n.id));
        $('Generate').click();
        await until(()=>$('Editor').hidden,'accepted submission closes editor');
        assert(!nodes.some(n=>!previousIds.has(n.id)&&n.images?.some(i=>i.local_repair)),'closes before generation completes');
        await until(()=>nodes.some(n=>!previousIds.has(n.id)&&n.images?.some(i=>i.local_repair)),'result delivered in background');
        assert($('Editor').hidden,'completed generation does not reopen editor');
        const accepted=await state(),request=accepted.submissions.at(-1);
        assert(accepted.submissions.length===before+1,'one submission');
        assert(request.transparent_png===true,'transparent PNG submitted');
        assert(request.n===3,'three repairs submitted in one request');
        assert(request.resolution==='2K'||request.resolution_tier==='2K'||request.capability_parameters?.resolution_tier==='2K','manual resolution submitted');
        assert(request.model==='gpt-image-2.5-suburst','preferred model submitted');
        assert(request.reference_images.length===1&&request.local_repair.source.url==='/assets/source.png','only cropped input submitted');
        const result=nodes.findLast(n=>!previousIds.has(n.id)&&n.images?.some(i=>i.local_repair));
        assert(result&&result.id!=='layer-source','original kept with separate output');
        assert(request.local_repair.version===2,'new soft brush recipe');
        await open(result.id);
        assert(!$('Result').hidden&&$('Result').querySelectorAll('option').length===3,'same-run repair results can be switched');
        const originalChoice=$('Result').value,otherChoice=[...$('Result').querySelectorAll('option')].find(option=>option.value!==originalChoice).value;
        const originalX=Number($('X').value);
        edit('X',originalX+11);
        edit('Result',otherChoice);
        await until(()=>$('Status').textContent===tr('smart.repair.adjustHint'),'switch result');
        assert(Number($('X').value)===originalX,'other result has independent transform');
        edit('X',originalX+22);
        edit('Result',originalChoice);
        await until(()=>$('Status').textContent===tr('smart.repair.adjustHint'),'switch back');
        assert(Number($('X').value)===originalX+11,'switch preserves per-result draft');
        assert($('Reset').localName==='ic-icon-button'&&$('Compare').localName==='ic-icon-button','shared icon actions');
        $('Compare').click();assert($('Compare').pressed,'compare toggle');$('Compare').click();
        const initialX=Number($('X').value);
        canvas.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true}));
        assert(Number($('X').value)===initialX+1,'keyboard adjusts patch without navigating images');
        edit('X',120);edit('Scale',120,'input');edit('Feather',7,'input');
        $('Feather').dispatchEvent(new Event('change',{bubbles:true}));
        const x=Number($('X').value);
        editor.close();await open(result.id);
        assert(Number($('X').value)===x&&Number($('Feather').value)===7,'adjustment draft survives reopen');
        window.StudioI18n.set('en');
        assert($('Heading').textContent===tr('smart.repair.adjust'),'dynamic English heading');
        assert($('X').getAttribute('label')===tr('smart.repair.x'),'English field labels');
        $('Save').click();
        await until(()=>$('Status').textContent===tr('smart.repair.saved'),'save composition');
        const saved=await state(),media=saved.canvas.nodes.find(n=>n.id===result.id).images[0];
        assert(media.url==='/assets/adjusted.png'&&media.local_repair.feather===7,'persist flattened output and recipe');
        assert(media.local_repair.transform.x===x,'persist original-pixel transform');
        assert(saved.submissions.length===before+1,'adjustment does not regenerate');
        $('Psd').click();await until(async()=>(await state()).psdExports.length>0,'PSD request');
        await until(()=>!$('Psd').disabled,'PSD complete');
        editor.close();await open(result.id);
        assert(Number($('X').value)===x&&$('Save').disabled,'saved recipe reopens cleanly');
        window.StudioI18n.set('zh');
        assert($('Heading').textContent===tr('smart.repair.adjust'),'Chinese restored');
        await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
        assert($('Canvas').getContext('2d').getImageData(400,200,1,1).data[0]!==228,'language switch retains rendered original');
        editor.close();
        await window.SmartCanvasModules.generationRun.regenerate({nodeId:result.id});
        const regenerated=(await state()).submissions.at(-1);
        assert(regenerated.local_repair.source.url==='/assets/source.png','regeneration preserves repair composition');
        const legacyDiameter=nodes.find(n=>n.id===result.id).images[0].local_repair.feather*2;
        window.SmartCanvasModules.canvasMutation.update({nodeId:result.id,mutate:node=>{node.images[0].local_repair.version=1;delete node.localRepairAdjustmentDrafts;},options:{render:false,select:false}});
        await open(result.id);
        assert(Number($('Feather').value)===legacyDiameter&&!$('Save').disabled,`legacy feather converts to brush diameter: ${$('Feather').value} / ${legacyDiameter}, save disabled=${$('Save').disabled}`);
        editor.close();await open(result.id);
        assert(Number($('Feather').value)===legacyDiameter,'legacy draft does not double diameter again');
        $('Save').click();await until(()=>$('Status').textContent===tr('smart.repair.saved'),'save upgraded mask');
        assert(nodes.find(n=>n.id===result.id).images[0].local_repair.version===2,'explicit save upgrades recipe');
        report.textContent='PASS: submit close/failure, soft edge mask, icon actions, frame resize, presets, transparent PNG, draft, save, i18n, PSD';
    } catch(error){report.textContent='FAIL: '+error.message;console.error(error);}
};

window.addEventListener('load',()=>{
    const timer=setInterval(()=>{
        const bar=document.getElementById('fixture-controls');if(!bar)return;clearInterval(timer);
        const button=document.createElement('button');button.textContent='Open saved repair';bar.append(button);
        button.onclick=()=>{const result=nodes.findLast(n=>n.images?.some(i=>i.local_repair));if(result)window.SmartCanvasModules.imageStudio.open({nodeId:result.id,mode:'local-repair'});};
    },50);
});
